# Integer
age = 27
print(type(age))

# Float
price = 99.50
print(type(price))

# String
name = "Kunal"
print(type(name))

# Boolean
is_student = True
print(type(is_student))

# List
numbers = [10, 20, 30]
print(type(numbers))

# Tuple
marks = (70, 80, 90)
print(type(marks))

# Set
unique_numbers = {1, 2, 3}
print(type(unique_numbers))

# Dictionary
student = {"name": "Kunal", "age": 27}
print(type(student))

# None
result = None
print(type(result))